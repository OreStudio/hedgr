#ifndef HEDGR_IMGUI_APP_GL_TEXTURE_HPP
#define HEDGR_IMGUI_APP_GL_TEXTURE_HPP

#include <GL/glew.h>

namespace hedgr::imgui::app {

/**
 * @brief Uploads RGBA pixels as a linear-filtered texture.
 *
 * The one place a decoded image becomes a texture. The live graphics context
 * is the caller's responsibility, as is deleting the texture.
 */
[[nodiscard]] inline unsigned int upload_rgba(const unsigned char* pixels,
    int width, int height) {
    unsigned int texture = 0;
    glGenTextures(1, &texture);
    glBindTexture(GL_TEXTURE_2D, texture);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, width, height, 0, GL_RGBA,
        GL_UNSIGNED_BYTE, pixels);
    return texture;
}

}

#endif
